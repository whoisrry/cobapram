CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT        NOT NULL CHECK (char_length(name) BETWEEN 1 AND 100),
    -- Aplikasi selalu menyimpan email dalam huruf kecil; CHECK menjamin
    -- UNIQUE berlaku tanpa membedakan huruf besar/kecil.
    email         TEXT        NOT NULL CHECK (email = lower(email) AND char_length(email) BETWEEN 3 AND 254),
    password_hash TEXT        NOT NULL,
    role          TEXT        NOT NULL CHECK (role IN ('client', 'admin')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT users_email_key UNIQUE (email)
);

CREATE TABLE tickets (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    subject    TEXT        NOT NULL CHECK (char_length(subject) BETWEEN 1 AND 200),
    body       TEXT        NOT NULL CHECK (char_length(body) BETWEEN 1 AND 10000),
    status     TEXT        NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'in_progress', 'closed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Daftar tiket milik client (WHERE user_id = ?), sekaligus menjadi index
-- untuk foreign key user_id.
CREATE INDEX tickets_user_id_status_idx ON tickets (user_id, status);
-- Daftar tiket admin: filter status lalu urut updated_at terbaru.
CREATE INDEX tickets_status_updated_at_idx ON tickets (status, updated_at DESC);
-- Daftar tiket admin tanpa filter status.
CREATE INDEX tickets_updated_at_idx ON tickets (updated_at DESC);

CREATE TABLE replies (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id  BIGINT      NOT NULL REFERENCES tickets (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    body       TEXT        NOT NULL CHECK (char_length(body) BETWEEN 1 AND 10000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Riwayat balasan per tiket, urut waktu.
CREATE INDEX replies_ticket_id_created_at_idx ON replies (ticket_id, created_at);
-- Index untuk foreign key user_id (dipakai saat cek ON DELETE RESTRICT).
CREATE INDEX replies_user_id_idx ON replies (user_id);

